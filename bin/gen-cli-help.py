#!/usr/bin/env python3
"""Regenerate clients/go/ultima/cmdhelp_data.go.

The supported-command set (names, arity, groups) comes from the registry
in lib/commands/table.go; syntax/summary/since come from the Redis 7.2.7
command metadata (src/commands/*.json) so `help <command>` matches the
compat target. The output file is committed; regeneration is a dev-time
step that needs a redis-7.2.7 checkout:

    REDIS_SRC=note/redis-7.2.7 python3 bin/gen-cli-help.py
"""

import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE_GO = os.path.join(REPO, "lib/commands/table.go")
OUT_GO = os.path.join(REPO, "clients/go/ultima/cmdhelp_data.go")
REDIS_SRC = os.environ.get("REDIS_SRC", os.path.join(REPO, "note/redis-7.2.7"))

DEF_RE = re.compile(
    r'^\s*def\("([a-z0-9_]+)",\s*(-?\d+),\s*\[\]string\{[^}]*\},'
    r'\s*-?\d+,\s*-?\d+,\s*\d+,\s*"([a-z_]+)",'
)


def parse_table():
    cmds = []
    for lineno, line in enumerate(open(TABLE_GO), 1):
        line = line.rstrip("\n")
        if not line.lstrip().startswith("def("):
            continue
        m = DEF_RE.match(line)
        if not m:
            sys.exit(f"table.go:{lineno}: unparsable def line: {line}")
        cmds.append((m.group(1), m.group(3)))  # name, group
    return cmds


def render_arg(a):
    t = a["type"]
    if t == "oneof":
        inner = " | ".join(render_arg(c) for c in a["arguments"])
    elif t == "block":
        inner = " ".join(render_arg(c) for c in a["arguments"])
    elif t == "pure-token":
        inner = a["token"]
    else:
        inner = a["name"]
    if "token" in a and t != "pure-token":
        inner = f"{a['token']} {inner}"
    if a.get("multiple"):
        inner = f"{inner} [{inner} ...]"
    if a.get("optional"):
        inner = f"[{inner}]"
    return inner


def redis_meta(name):
    path = os.path.join(REDIS_SRC, "src/commands", f"{name}.json")
    if not os.path.exists(path):
        return None
    doc = json.load(open(path))[name.upper()]
    syntax = name.upper()
    if doc.get("arguments"):
        syntax += " " + " ".join(render_arg(a) for a in doc["arguments"])
    return {
        "syntax": syntax,
        "summary": doc.get("summary", ""),
        "since": doc.get("since", ""),
    }


def go_str(s):
    # json.dumps produces a Go-compatible double-quoted string literal.
    return json.dumps(s, ensure_ascii=True)


def main():
    cmds = parse_table()
    entries = []
    missing = []
    for name, group in cmds:
        meta = redis_meta(name)
        if meta is None:
            missing.append(name)
            meta = {"syntax": name.upper(), "summary": "", "since": ""}
        entries.append((name, group, meta))
    if missing:
        print("warning: no Redis metadata for: " + ", ".join(missing),
              file=sys.stderr)

    entries.sort(key=lambda e: e[0])
    out = [
        "// Code generated by bin/gen-cli-help.py; DO NOT EDIT.",
        "// Regenerate: REDIS_SRC=note/redis-7.2.7 python3 bin/gen-cli-help.py",
        "",
        "package ultima",
        "",
        "var cmdHelpEntries = []cmdHelpEntry{",
    ]
    for name, group, meta in entries:
        out.append(
            "\t{Name: %s, Group: %s, Syntax: %s, Summary: %s, Since: %s},"
            % (go_str(name), go_str(group), go_str(meta["syntax"]),
               go_str(meta["summary"]), go_str(meta["since"]))
        )
    out.append("}")
    out.append("")
    with open(OUT_GO, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT_GO}: {len(entries)} commands")


if __name__ == "__main__":
    main()
